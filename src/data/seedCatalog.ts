function createSeedOrder(
  id: string,
  reference: string,
  createdAt: string,
  customerName: string,
  whatsapp: string,
  commune: string,
  landmark: string,
  items: CodOrder['items'],
  status: CodOrder['status']
): CodOrder {
  const totalFcfa = items.reduce((sum, item) => sum + item.unitPriceFcfa * item.quantity, 0);
  return {
    id,
    reference,
    createdAt,
    customerName,
    whatsapp,
    commune,
    landmark,
    items,
    totalFcfa,
    status,
    whatsappMessage: buildWhatsAppOrderMessage({
      reference,
      customerName,
      whatsapp,
      commune,
      landmark,
      items,
      totalFcfa,
    }),
  };
}

